"""Fresh, frozen procedural inputs for testing arrangement acceptance.

This emitter does not use aligner templates or inspect prediction outputs. Its
explicit MIDI voicings, registers, rhythms and silent intervals differ from the
original rich-quality suite. Labels and PCM are generated by separate branches;
only the untimed label branch may be given to inference. This is a diagnostic
pack, not real guitar audio or a statistical generalization estimate.
"""
