def recipes() -> list[dict]:
    """Return the complete frozen 4-by-4 design; no adaptive sampling."""
    result = []
    for family_index, family in enumerate(FAMILIES):
        for variant_index, variant in enumerate(_VARIANTS):
            recipe = copy.deepcopy(variant)
            recipe.update(family=family, split="fresh_validation", level=variant_index + 1,
                          variant_index=variant_index, seed=variant["seed"] + family_index * 101,
                          synthesis="Fresh explicit MIDI close/spread voicings and independent six-harmonic pulses",
                          distractor_policy="All added bass and melody fundamentals are existing chord tones")
            result.append(recipe)
    return result


def _silence(cursor: int, seconds: float, sample_rate: int, role: str) -> dict:
    return {"start_seconds": cursor / sample_rate,
            "end_seconds": (cursor + round(seconds * sample_rate)) / sample_rate,
            "label": "N", "midi_notes": [], "pitch_classes": [], "silence_role": role}


def events_for(recipe: dict, sample_rate: int = SAMPLE_RATE) -> list[dict]:
    """Audio-event branch; every interval is exactly sample aligned."""
    labels = PROGRESSIONS[recipe["family"]]
    events = [_silence(0, recipe["intro_seconds"], sample_rate, "intro")]
    cursor = round(events[-1]["end_seconds"] * sample_rate)
    gaps = {3, 6} if recipe["family"] == "section_repeat" else {len(labels) // 2}
    duration_pattern = (1.37, 2.63, 1.91, 2.27, 1.54, 2.81, 1.72, 2.39, 1.83)
    for index, label in enumerate(labels):
        if index in gaps:
            gap = _silence(cursor, recipe["middle_seconds"] + (0.37 if index == 6 else 0),
                           sample_rate, "middle")
            events.append(gap)
            cursor = round(gap["end_seconds"] * sample_rate)
        variant = recipe["variant_index"]
        seconds = duration_pattern[(index + variant) % len(duration_pattern)]
        seconds += (variant * 0.071) + (-0.093 if index % 2 else 0.119)
        count = round(seconds * sample_rate)
        notes = [note + recipe["transposition"] for note in VOICINGS[recipe["voicing_bank"]][label]]
        events.append({"start_seconds": cursor / sample_rate, "end_seconds": (cursor + count) / sample_rate,
                       "label": rich_quality_suite.transpose(label, recipe["transposition"]),
                       "recipe_label": label, "midi_notes": notes,
                       "pitch_classes": sorted({note % 12 for note in notes})})
        cursor += count
    events.append(_silence(cursor, recipe["outro_seconds"], sample_rate, "outro"))
    return events


def _voice(note: int, count: int, sample_rate: int, phase: float, *, attack: float,
           lag: float, stroke: float, decay: float, harmonic_tilt: float) -> np.ndarray:
    time = np.arange(count) / sample_rate
    frequency = 440.0 * 2.0 ** ((note - 69) / 12.0)
    oscillator = sum(np.sin(2 * np.pi * frequency * harmonic * time + phase * (harmonic + 0.3))
                     / harmonic ** harmonic_tilt for harmonic in range(1, 7))
    envelope = np.zeros(count)
    for onset in np.arange(lag, count / sample_rate, stroke):
        elapsed = time - onset
        envelope += np.clip(elapsed / attack, 0, 1) * np.exp(-np.maximum(elapsed, 0) / decay)
    fade = min(round(0.026 * sample_rate), count // 2)
    if fade:
        envelope[-fade:] *= np.linspace(1, 0, fade)
    return oscillator * envelope


def render(recipe: dict, events: list[dict], sample_rate: int = SAMPLE_RATE) -> np.ndarray:
    """No chord-template calls, reference-file reads or cross-gap ringing."""
    rng = np.random.default_rng(recipe["seed"])
    signal = np.zeros(round(events[-1]["end_seconds"] * sample_rate))
    for event in events:
        if event["label"] == "N":
            continue
        start, end = (round(event[key] * sample_rate) for key in ("start_seconds", "end_seconds"))
        notes = event["midi_notes"]
        # Alternating strokes change direction, relative levels and register
        # salience while leaving the declared fundamental pitch set intact.
        order = list(reversed(notes)) if recipe["variant_index"] % 2 else notes
        for index, note in enumerate(order):
            signal[start:end] += (0.71 + 0.07 * ((index + recipe["variant_index"]) % 4)) * _voice(
                note, end - start, sample_rate, rng.uniform(0, 2 * np.pi),
                attack=recipe["attack_seconds"], lag=index * recipe["string_lag_seconds"],
                stroke=recipe["stroke_seconds"], decay=recipe["decay_seconds"],
                harmonic_tilt=2.15 + recipe["variant_index"] * 0.13)
        if recipe["condition"] == "bass_melody":
            # Root-bass derives from the explicit MIDI bass, not a classifier
            # pitch template. Melody cycles only through existing fundamentals.
            signal[start:end] += 1.3 * _voice(notes[0] - 12, end - start, sample_rate, 0.41,
                attack=0.061, lag=0, stroke=0.47, decay=0.74, harmonic_tilt=2.31)
            chunk = round(0.43 * sample_rate)
            for offset in range(0, end - start, chunk):
                stop = min(end, start + offset + chunk)
                note = notes[1 + ((offset // chunk) % (len(notes) - 1))] + 12
                signal[start + offset:stop] += 0.43 * _voice(note, stop - start - offset,
                    sample_rate, 1.73, attack=0.028, lag=0, stroke=0.43, decay=0.36,
                    harmonic_tilt=2.47)
    peak = np.max(np.abs(signal))
    return signal * (0.73 / peak) if peak else signal


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def untimed_for(recipe: dict, identifier: str, title: str, audio_hash: str) -> dict:
    """Label-only branch: cannot see events, audio length, silence or timings."""
    result = {"schema_version": chart_aligner.SCHEMA,
        "recording": {"id": identifier, "title": title, "audio_sha256": audio_hash},
        "sequence": [rich_quality_suite.transpose(label, recipe["transposition"])
                     for label in PROGRESSIONS[recipe["family"]]],
        "mode": "finite", "start_policy": "first", "end_policy": "last",
        "metadata": {"source_references": [{"source": "Fresh frozen recipe labels only"}],
                     "note": "No reference times, durations, silence markers or gap locations supplied"}}
    chart_aligner.validate_untimed_chart(result)
    return result


def count_controls(untimed: dict, family: str) -> dict[str, dict]:
    """Declared wrong-count sequences, constructed without a timed reference."""
    if family != "section_repeat":
        return {}
    labels = untimed["sequence"]
    result = {}
    for name, sequence in (("missing_repeat", labels[:-3]), ("extra_repeat", labels + labels[:3])):
        chart = copy.deepcopy(untimed)
        chart["sequence"] = list(sequence)
        chart["metadata"]["screen_control"] = name
        chart_aligner.validate_untimed_chart(chart)
        result[name] = chart
    return result


def generate(directory: Path, sample_rate: int = SAMPLE_RATE) -> dict:
    """Atomically publish once. Refuse overwrite and clean failed staging."""
    directory = Path(directory)
    if directory.exists() or directory.is_symlink():
        raise ValueError("Acceptance output directory already exists; choose a new directory")
    if not isinstance(sample_rate, int) or isinstance(sample_rate, bool) or not 8000 <= sample_rate <= 96000:
        raise ValueError("Sample rate must be an integer from 8000 to 96000 Hz")
    directory.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix=f".{directory.name}-", dir=directory.parent))
    cases = []
    try:
        for recipe in recipes():
            identifier = f"fresh-{recipe['family']}-{recipe['condition']}"
            title = f"Fresh {recipe['family'].replace('_', ' ')} / {recipe['condition'].replace('_', ' ')} / transpose {recipe['transposition']}"
            folder = staging / "cases" / identifier
            folder.mkdir(parents=True)
            events = events_for(recipe, sample_rate)
            signal = render(recipe, events, sample_rate)
            pcm = np.rint(signal * 32767).astype("<i2").tobytes()
            with wave.open(str(folder / "audio.wav"), "wb") as output:
                output.setnchannels(1)
                output.setsampwidth(2)
                output.setframerate(sample_rate)
                output.writeframes(pcm)
            audio_hash = sha(folder / "audio.wav")
            reference = {"schema_version": "1.0", "recording": {"id": identifier, "title": title,
                "duration_seconds": len(signal) / sample_rate, "sample_rate_hz": sample_rate,
                "audio_sha256": audio_hash, "provenance": "Original fresh explicit MIDI procedural synthesis"},
                "analysis": {"id": f"{identifier}-reference", "algorithm": "fixture-reference", "version": "1.0",
                             "runtime_seconds": 0, "parameters": recipe}, "chords": events}
            lab.validate_chart(reference)
            lab.write_json(folder / "reference.json", reference)
            untimed = untimed_for(recipe, identifier, title, audio_hash)
            lab.write_json(folder / "untimed.json", untimed)
            controls = {}
            for name, chart in count_controls(untimed, recipe["family"]).items():
                filename = f"untimed-{name}.json"
                lab.write_json(folder / filename, chart)
                controls[name] = {"path": f"cases/{identifier}/{filename}", "sha256": sha(folder / filename)}
            cases.append({"id": identifier, "name": title, "level": recipe["level"],
                "condition": recipe["condition"], "split": recipe["split"], "family": recipe["family"],
                "recipe": recipe, "audio": f"cases/{identifier}/audio.wav",
                "reference": f"cases/{identifier}/reference.json", "untimed": f"cases/{identifier}/untimed.json",
                "untimed_controls": controls, "pcm_sha256": hashlib.sha256(pcm).hexdigest(),
                "audio_sha256": audio_hash, "reference_sha256": sha(folder / "reference.json"),
                "untimed_sha256": sha(folder / "untimed.json")})
        manifest = {"suite_version": SCHEMA, "sample_rate_hz": sample_rate,
            "generator_sha256": sha(Path(__file__)), "cases": cases,
            "dependencies_sha256": {"label_semantics": sha(Path(rich_quality_suite.__file__)),
                                     "chart_validation": sha(Path(chart_aligner.__file__)),
                                     "artifact_validation": sha(Path(lab.__file__))},
            "freeze_protocol": "Publish before choosing guarded acceptance thresholds; do not alter recipes after viewing validation outcomes",
            "limitations": ["Procedural oscillators, not recorded guitar, voice, drums or a full song mix",
                "Fresh voicings and recipes relative to the earlier suite, not independent sampled performance data",
                "Finite correct-label charts supply harmonic order/count only; silent gap locations are not supplied",
                "Wrong-count control charts are explicit hypotheses, never a correction to the reference"]}
        lab.write_json(staging / "manifest.json", manifest)
        if directory.exists() or directory.is_symlink():
            raise ValueError("Acceptance output directory appeared during generation")
        staging.rename(directory)
        return manifest
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate",))
    parser.add_argument("--output-dir", type=Path, default=lab.GENERATED / "acceptance-validation-v1")
    args = parser.parse_args()
    result = generate(args.output_dir)
    print(json.dumps({"cases": len(result["cases"]), "output_dir": str(args.output_dir),
                      "manifest_sha256": sha(args.output_dir / "manifest.json"),
                      "generator_sha256": result["generator_sha256"]}, indent=2))


if __name__ == "__main__":
    main()
